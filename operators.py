#math operators
# example:
# +,-,/,//,*,**,%

val=5
val2=2
add=val+val2
print(f"{val}+{val2} = {add}")

sub = val-val2 
print(f"{val}-{val2} = {sub}")

div= val/val2
print(f"{val}/{val2} = {div}")

abs= val//val2
print(f"{val}//{val2} = {abs}")


multi= val*val2
print(f"{val}*{val2} = {multi}")

epo=val**val2
print(f"{val}**{val2} = {epo}")

mod= val%val2
print(f"{val}%{val2} = {mod}")
